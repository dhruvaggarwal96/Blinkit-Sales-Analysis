-- ============================================================
-- Sales analysis
-- All results describe this sample dataset, not actual Blinkit data.
-- Revenue assumes price is the per-unit price and revenue = quantity * price.
-- ============================================================

-- 1. Calculate total revenue in the sample dataset.
SELECT SUM(price * quantity) AS total_revenue
FROM orders;

-- 2. Find total number of orders.
SELECT COUNT(*) AS total_orders
FROM orders;

-- 3. Find total unique customers.
SELECT COUNT(DISTINCT customer_id) AS unique_customers
FROM orders;

-- 4. Calculate average order value.
-- Each row represents one order because order_id is the primary key.
SELECT AVG(price * quantity) AS average_order_value
FROM orders;

-- 5. Find the top 10 highest-spending customers.
SELECT
    customer_id,
    MAX(customer_name) AS customer_name,
    SUM(price * quantity) AS total_spending
FROM orders
GROUP BY customer_id
ORDER BY total_spending DESC, customer_id
LIMIT 10;

-- 6. Find total revenue generated by each city.
SELECT
    city,
    SUM(price * quantity) AS total_revenue
FROM orders
GROUP BY city
ORDER BY total_revenue DESC;

-- 7. Find total revenue by product category.
SELECT
    category,
    SUM(price * quantity) AS total_revenue
FROM orders
GROUP BY category
ORDER BY total_revenue DESC;

-- 8. Find total quantity sold for every product.
SELECT
    category,
    product_name,
    SUM(quantity) AS total_quantity
FROM orders
GROUP BY category, product_name
ORDER BY total_quantity DESC;

-- 9. Find monthly revenue by year and month.
SELECT
    YEAR(order_date) AS revenue_year,
    MONTH(order_date) AS month_number,
    MONTHNAME(order_date) AS month_name,
    SUM(price * quantity) AS revenue
FROM orders
GROUP BY YEAR(order_date), MONTH(order_date), MONTHNAME(order_date)
ORDER BY revenue_year, month_number;

-- 10. Identify the highest-revenue month across all years.
SELECT
    YEAR(order_date) AS revenue_year,
    MONTH(order_date) AS month_number,
    MONTHNAME(order_date) AS month_name,
    SUM(price * quantity) AS revenue
FROM orders
GROUP BY YEAR(order_date), MONTH(order_date), MONTHNAME(order_date)
ORDER BY revenue DESC
LIMIT 1;

-- 11. Find the top five products by quantity sold.
SELECT
    category,
    product_name,
    SUM(quantity) AS total_quantity
FROM orders
GROUP BY category, product_name
ORDER BY total_quantity DESC, category, product_name
LIMIT 5;

-- 12. Find the top five products by revenue.
SELECT
    category,
    product_name,
    SUM(quantity * price) AS total_revenue
FROM orders
GROUP BY category, product_name
ORDER BY total_revenue DESC, category, product_name
LIMIT 5;

-- 13. Calculate average delivery time for each city.
SELECT
    city,
    AVG(delivery_time) AS average_delivery_time
FROM orders
GROUP BY city
ORDER BY average_delivery_time;

-- 14. Find cities where average delivery time exceeds 20 minutes.
SELECT
    city,
    AVG(delivery_time) AS average_delivery_time
FROM orders
GROUP BY city
HAVING AVG(delivery_time) > 20
ORDER BY average_delivery_time DESC;

-- 15. Calculate total spending per customer (customer-level value).
SELECT
    customer_id,
    MAX(customer_name) AS customer_name,
    SUM(price * quantity) AS total_spending
FROM orders
GROUP BY customer_id
ORDER BY total_spending DESC;

-- 16. Segment customers based on total spending.
-- Premium: > 1500
-- Gold: 1000 to 1500 inclusive
-- Silver: 500 to less than 1000
-- Regular: < 500
SELECT
    customer_id,
    MAX(customer_name) AS customer_name,
    SUM(quantity * price) AS total_spending,
    CASE
        WHEN SUM(quantity * price) > 1500 THEN 'Premium'
        WHEN SUM(quantity * price) >= 1000 THEN 'Gold'
        WHEN SUM(quantity * price) >= 500 THEN 'Silver'
        ELSE 'Regular'
    END AS customer_segment
FROM orders
GROUP BY customer_id
ORDER BY total_spending DESC;

-- 17. Find repeat customers (more than one order).
SELECT
    customer_id,
    MAX(customer_name) AS customer_name,
    COUNT(*) AS order_count
FROM orders
GROUP BY customer_id
HAVING COUNT(*) > 1
ORDER BY order_count DESC, customer_id;

-- 18. Find customers whose total spending is above average customer spending.
SELECT
    customer_id,
    MAX(customer_name) AS customer_name,
    SUM(price * quantity) AS customer_spending
FROM orders
GROUP BY customer_id
HAVING SUM(price * quantity) > (
    SELECT AVG(customer_spending)
    FROM (
        SELECT SUM(price * quantity) AS customer_spending
        FROM orders
        GROUP BY customer_id
    ) AS customer_spending_table
)
ORDER BY customer_spending DESC;
